"""§multi-cli (§21): разовые запросы к `grok agent stdio` вне чат-сессий —
список моделей (с уровнями рассуждения) из ответа `session/new`."""

from __future__ import annotations

import asyncio
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path
from typing import Any

import structlog

from . import cli_registry, grok_auth
from .acp_common import has_http_code
from .acp_client import AcpClient, AcpClosed, AcpRpcError

log = structlog.get_logger("grok_rpc")

CLI_TYPE = "grok"
GROK_HOOK = str(Path(__file__).resolve().parent.parent / "grok_hook.py")


_CACHE_TTL = 600.0
_cache: dict[str, Any] = {"ts": 0.0, "stamp": None, "data": None}


def _toml_list(items: list[str]) -> str:
    return "[" + ", ".join(json.dumps(i) for i in items) + "]"


GATEWAY_KEY_ENV = "GROK_HEDGEHOG_GATEWAY_KEY"
_BACKENDS = ("chat_completions", "responses", "messages")


def gateway_key(model_id: str) -> str:
    """Ключ записи [model.<key>] в config.toml для id модели шлюза."""
    import re
    return re.sub(r"[^A-Za-z0-9_.-]", "_", model_id)[:80] or "model"


def _gateway_base(base: str) -> str:
    """base_url для OpenAI-подобных бэкендов Grok обязан включать /v1."""
    base = base.rstrip("/")
    return base if base.endswith("/v1") else base + "/v1"


def alt_config(rec: dict) -> str:
    """Секции config.toml для API-ключа / шлюза (rec — grok_auth.alt_record())."""
    if not rec:
        return ""
    # ключ лежит в env процесса grok — не отдаём его в окружение shell-команд агента
    out = ['\n[shell_environment_policy]\ninherit = "all"\n'
           'ignore_default_excludes = false\n'
           f'exclude = ["XAI_API_KEY", "{GATEWAY_KEY_ENV}"]\n']
    if rec.get("method") == "api_key":
        # ключ из XAI_API_KEY; pin — чтобы сессия подписки не перекрыла ключ
        out.append('\n[auth]\npreferred_method = "api_key"\n')
        if rec.get("base_url"):
            out.append(f"\n[endpoints]\nxai_api_base_url = "
                       f"{json.dumps(_gateway_base(rec['base_url']))}\n")
    elif rec.get("method") == "gateway" and rec.get("base_url"):
        backend = rec.get("api_backend") if rec.get("api_backend") in _BACKENDS \
            else "chat_completions"
        base = _gateway_base(rec["base_url"]) if backend != "messages" \
            else rec["base_url"].rstrip("/")
        models = [m for m in rec.get("models") or [] if isinstance(m, dict) and m.get("id")]
        for m in models:
            out.append(f"\n[model.{json.dumps(gateway_key(m['id']))}]\n"
                       f"model = {json.dumps(m['id'])}\n"
                       f"name = {json.dumps(str(m.get('name') or m['id']))}\n"
                       f"base_url = {json.dumps(base)}\n"
                       f"env_key = {json.dumps(GATEWAY_KEY_ENV)}\n"
                       f"api_backend = {json.dumps(backend)}\n")
        active = rec.get("active_id") or (models[0]["id"] if models else "")
        if active:
            out.append(f"\n[models]\ndefault = {json.dumps(gateway_key(active))}\n")
    return "".join(out)


def permission_config(protect: list[str], alt: dict | None = None) -> str:
    """config.toml управляемого GROK_HOME: правила прав поверх режимов Grok.
    `ask = MCPTool(*)` — Grok спрашивает про КАЖДЫЙ MCP-инструмент (иначе он
    вызывает их молча) → session/request_permission → политика Ёжика; deny на
    чужие секреты работает и для shell-команд, читающих эти пути."""
    home = str(Path.home())
    secret_dirs = [f"{home}/.ssh", f"{home}/.codex", f"{home}/.claude",
                   f"{home}/.gemini", f"{home}/.grok", f"{home}/.aws",
                   f"{home}/.config/gcloud"]
    deny = [f"{op}({p}/**)" for p in secret_dirs for op in ("Read", "Edit")]
    deny += [f"{op}({p})" for p in protect for op in ("Read", "Edit")]
    deny += [f"{op}(**/{pat})" for pat in (".env", ".env.*", "*.pem", "id_rsa", "id_ed25519")
             for op in ("Read", "Edit")]
    # окружение процессов (в т.ч. самого grok с XAI_API_KEY): /proc/<pid>/environ
    deny += ["Read(/proc/**)"]
    deny += ["Bash(sudo *)", "Bash(su *)"]
    hook = f"{sys.executable} {GROK_HOOK}"
    # §cli-pins: политика «точно» (HEDGEHOG_CLI_AUTO_UPDATE=0) — Grok не
    # обновляет себя сам, версию ведёт Ёжик (compat.json → update_self)
    cli = "" if cli_registry.cli_auto_update() else "[cli]\nauto_update = false\n\n"
    return ("# generated by Hedgehog (core/grok_rpc.py) - manual edits are overwritten\n"
            + cli +
            "[permission]\n"
            f"ask = {_toml_list(['MCPTool(*)'])}\n"
            f"deny = {_toml_list(deny)}\n\n"
            # PreToolUse: обращение к пути вне cwd -> ask (grok_hook.py)
            "[[hooks.PreToolUse]]\n"
            'matcher = "read_file|list_dir|grep|run_terminal_command"\n'
            f"hooks = [ {{ type = \"command\", command = {json.dumps(hook)}, timeout = 10 }} ]\n"
            + alt_config(alt or {}))


def prepare_home(*, for_login: bool = False) -> Path | None:
    """Подготовить управляемый GROK_HOME: каталог 0700, config.toml с правилами,
    разовый перенос входа из ~/.grok (чтобы вход не терялся). В режиме ключа/шлюза
    — отдельный каталог без токена подписки. None — режим выключен (явный
    GROK_HOME или HEDGEHOG_GROK_HOME=system)."""
    home = grok_auth.managed_home()
    if home is None or os.environ.get("GROK_HOME"):
        return None
    rec = {} if for_login else grok_auth.alt_record()
    if rec:
        home = grok_auth.alt_home()
    home.mkdir(parents=True, exist_ok=True)
    os.chmod(home, 0o700)
    cfg = home / "config.toml"
    want = permission_config(grok_auth.protected_paths(), rec)
    try:
        if not cfg.exists() or cfg.read_text("utf-8") != want:
            cfg.write_text(want, "utf-8")
    except OSError as e:
        log.warning("grok.config_write_failed", err=str(e))
    tok = home / "auth.json"
    legacy = Path.home() / ".grok" / "auth.json"
    if not rec and not tok.exists() and legacy.is_file():
        try:
            shutil.copy2(legacy, tok)
            os.chmod(tok, 0o600)
            log.info("grok.auth_migrated")
        except OSError as e:
            log.warning("grok.auth_migrate_failed", err=str(e))
    return home


def grok_extra_env(*, for_login: bool = False) -> dict[str, str]:
    """Доп. env процесса grok: песочница по умолчанию ВЫКЛ (Landlock в контейнерах
    ненадёжен; HEDGEHOG_GROK_SANDBOX=workspace|strict|… включает профиль) и
    отключение подхвата ~/.claude (скиллы/хуки/MCP/правила/агенты — это чужой
    код и инструкции Claude Code, а не часть чата Grok)."""
    env = {"GROK_SANDBOX": os.environ.get("HEDGEHOG_GROK_SANDBOX", "off")}
    rec = {} if for_login else grok_auth.alt_record()
    if rec.get("method") == "api_key":
        env["XAI_API_KEY"] = rec["api_key"]
    elif rec.get("method") == "gateway":
        env[GATEWAY_KEY_ENV] = rec["api_key"]
    home = prepare_home(for_login=for_login)
    if home is not None:
        env["GROK_HOME"] = str(home)
    for k in ("SKILLS", "HOOKS", "MCPS", "RULES", "AGENTS"):
        env[f"GROK_CLAUDE_{k}_ENABLED"] = "false"
    return env


def _stamp() -> tuple | None:
    """Отпечаток входа: смена аккаунта/ключа/logout инвалидирует кэш моделей."""
    import hashlib
    rec = grok_auth.alt_record()
    alt = hashlib.sha256(json.dumps(
        [rec.get("method"), rec.get("api_key"), rec.get("base_url")]).encode()
    ).hexdigest()[:16] if rec else None
    try:
        st = grok_auth.token_path().stat()
        return (st.st_mtime_ns, st.st_size, alt)
    except OSError:
        return (None, None, alt)


def remember_models(session_new_result: Any) -> None:
    """Запомнить модели из ответа session/new (чат-сессия уже платит за него)."""
    data = parse_models(session_new_result)
    if data["models"]:
        _cache.update(ts=time.monotonic(), stamp=_stamp(), data=data)


def _cached() -> dict[str, Any] | None:
    if _cache["data"] is not None and time.monotonic() - _cache["ts"] < _CACHE_TTL \
            and _cache["stamp"] == _stamp():
        return _cache["data"]
    return None


def parse_models(res: Any) -> dict[str, Any]:
    """`session/new` result.models → формат models_list (как у Codex:
    models/names/efforts/defaultEfforts/current)."""
    m = res.get("models") if isinstance(res, dict) else None
    m = m if isinstance(m, dict) else {}
    ids: list[str] = []
    names: dict[str, str] = {}
    efforts: dict[str, list[str]] = {}
    defaults: dict[str, str] = {}
    avail = m.get("availableModels")
    for it in avail if isinstance(avail, list) else []:
        if not isinstance(it, dict):
            continue
        mid = it.get("modelId")
        if not isinstance(mid, str) or not mid or mid in names:
            continue
        ids.append(mid)
        nm = it.get("name")
        names[mid] = nm if isinstance(nm, str) and nm else mid
        meta = it.get("_meta") if isinstance(it.get("_meta"), dict) else {}
        effs = meta.get("reasoningEfforts")
        efforts[mid] = [e["id"] for e in (effs if isinstance(effs, list) else [])
                        if isinstance(e, dict) and isinstance(e.get("id"), str)]
        de = meta.get("reasoningEffort")
        if isinstance(de, str) and de:
            defaults[mid] = de
    cur = m.get("currentModelId")
    return {"models": ids, "names": names, "efforts": efforts,
            "defaultEfforts": defaults,
            "current": cur if isinstance(cur, str) else None}


async def probe_models(*, argv: list[str] | None = None,
                       timeout: float = 45.0) -> dict[str, Any]:
    """Проба для models_list. Не залогинен → AUTH_REQUIRED без запуска процесса;
    нет бинарника → NO_CLI."""
    base = {"cliType": CLI_TYPE, "models": [], "current": None, "raw": ""}
    binary = None
    if argv is None:
        binary = cli_registry.find_binary(CLI_TYPE)
        if binary is None:
            return {**base, "auth_state": "NO_CLI", "cli_present": False}
    rec = grok_auth.alt_record() if argv is None else {}
    if rec.get("method") == "gateway":
        # каталог моделей — выбранные при активации шлюза (CLI не запускаем)
        ms = [m for m in rec.get("models") or [] if isinstance(m, dict) and m.get("id")]
        return {**base, "models": [m["id"] for m in ms],
                "names": {m["id"]: str(m.get("name") or m["id"]) for m in ms},
                "current": rec.get("active_id") or (ms[0]["id"] if ms else None),
                "source": "gateway", "auth_state": "OK" if ms else "ERROR",
                "cli_present": True}
    if not rec and not grok_auth.is_logged_in():
        return {**base, "auth_state": "AUTH_REQUIRED", "cli_present": True}
    hit = _cached() if argv is None else None
    if hit is not None:
        return {**base, **hit, "auth_state": "OK", "cli_present": True}
    cmd = argv or [binary, "agent", "stdio"]
    env = cli_registry.spawn_env(CLI_TYPE, binary, grok_extra_env()) if binary else None
    client = AcpClient(cmd, cwd=tempfile.gettempdir(), env=env)
    try:
        await client.start()
        await client.request("initialize", {
            "protocolVersion": 1, "clientCapabilities": {}}, timeout=30)
        res = await client.request("session/new", {
            "cwd": tempfile.gettempdir(), "mcpServers": []}, timeout=timeout)
    except (OSError, AcpClosed, AcpRpcError, asyncio.TimeoutError) as e:
        low = str(e).lower()
        state = ("AUTH_REQUIRED" if has_http_code(low, 401) or any(
            m in low for m in ("not logged in", "unauthor", "unauthenticated",
                               "log in", "login required")) else "ERROR")
        log.warning("grok.models_probe_failed", err=repr(e), state=state)
        return {**base, "auth_state": state, "cli_present": True}
    finally:
        await client.close()
    data = parse_models(res)
    if not data["models"]:
        return {**base, "auth_state": "ERROR", "cli_present": True}
    if argv is None:
        _cache.update(ts=time.monotonic(), stamp=_stamp(), data=data)
    return {**base, **data, "auth_state": "OK", "cli_present": True}
