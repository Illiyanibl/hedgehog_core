"""§multi-cli (§20): авторизация OpenAI Codex CLI на сервере (вход ChatGPT).

`codex login --device-auth` — вход по коду устройства: CLI печатает ссылку
(https://auth.openai.com/codex/device) и одноразовый код; пользователь открывает
ссылку в любом браузере и вводит код. Обратно в Ёжик ничего слать не нужно:
процесс сам завершается кодом 0 и сохраняет токен в `$CODEX_HOME/auth.json`.
Интерфейс как у `AgyAuthManager`; фреймы — `auth_link {url, userCode}` и
`auth_result` (с `cliType: "codex"`). `auth_code` для Codex не используется.

ВНИМАНИЕ (проверено на 0.167.2): запуск `codex login --device-auth` СРАЗУ стирает
действующие учётные данные, не дожидаясь подтверждения нового входа.
"""

from __future__ import annotations

import asyncio
import json
import os
import re
from pathlib import Path

import structlog

from . import cli_registry
from ..i18n import Msg
from .auth_flow import ANSI_RE, URL_RE, SubprocessAuthFlow

log = structlog.get_logger("codex_auth")

CLI_TYPE = "codex"

_ANSI_RE, _URL_RE = ANSI_RE, URL_RE
_CODE_RE = re.compile(r"^[A-Z0-9]{4}-[A-Z0-9]{4,8}$")


# Режимы API-ключа/шлюза живут в ОТДЕЛЬНОМ CODEX_HOME (<data_dir>/codex-home-alt):
# `codex login --with-api-key` пишет в тот же auth.json, что и вход ChatGPT, и
# стёр бы подписку; отдельный каталог её не трогает и переключается туда-обратно.
_config = None
GATEWAY_KEY_ENV = "HEDGEHOG_CODEX_GATEWAY_KEY"


def configure(config) -> None:
    global _config
    _config = config


def alt_record() -> dict:
    """Активный нестандартный способ Codex ({} — подписка)."""
    if _config is None:
        return {}
    from . import auth_store
    rec = auth_store.load(_config, CLI_TYPE)
    if rec.get("method") in (auth_store.API_KEY, auth_store.GATEWAY) and rec.get("api_key"):
        return rec
    return {}


def alt_home() -> Path | None:
    return _config.data_dir / "codex-home-alt" if _config is not None else None


def alt_config_text(rec: dict) -> str:
    """config.toml альт-каталога: базовый URL ключа / провайдер шлюза."""
    import json as _json
    lines = ["# generated by Hedgehog (core/codex_auth.py) - manual edits are overwritten",
             # ключ лежит в env процесса codex — не отдаём его в окружение команд агента
             "[shell_environment_policy]", 'inherit = "all"',
             "ignore_default_excludes = false",
             f'exclude = ["{GATEWAY_KEY_ENV}", "OPENAI_API_KEY", "CODEX_API_KEY"]', ""]
    top: list[str] = []
    if rec.get("method") == "api_key" and rec.get("base_url"):
        top.append(f"openai_base_url = {_json.dumps(rec['base_url'].rstrip('/'))}")
    elif rec.get("method") == "gateway":
        base = rec.get("base_url", "").rstrip("/")
        base = base if base.endswith("/v1") else base + "/v1"
        top.append('model_provider = "hedgehog_gw"')
        lines += ["[model_providers.hedgehog_gw]", 'name = "Gateway"',
                  f"base_url = {_json.dumps(base)}",
                  f"env_key = {_json.dumps(GATEWAY_KEY_ENV)}",
                  'wire_api = "responses"']
    # верхнеуровневые ключи TOML обязаны идти ДО первой таблицы
    return "\n".join([lines[0], *top, *lines[1:]]) + "\n"


def prepare_alt_home() -> Path | None:
    """Каталог 0700 + актуальный config.toml. None — активен вход по подписке."""
    rec = alt_record()
    home = alt_home()
    if not rec or home is None:
        return None
    home.mkdir(parents=True, exist_ok=True)
    os.chmod(home, 0o700)
    cfg = home / "config.toml"
    want = alt_config_text(rec)
    try:
        if not cfg.exists() or cfg.read_text("utf-8") != want:
            cfg.write_text(want, "utf-8")
    except OSError as e:
        log.warning("codex_auth.alt_config_failed", err=str(e))
    return home


def codex_extra_env() -> dict[str, str]:
    """Доп. env процессов codex (сессии, app-server): CODEX_HOME альт-режима и ключ шлюза."""
    rec = alt_record()
    home = prepare_alt_home()
    if home is None:
        return {}
    env = {"CODEX_HOME": str(home)}
    if rec.get("method") == "gateway":
        env[GATEWAY_KEY_ENV] = rec["api_key"]
    return env


_LOGIN_KEY_TIMEOUT = 30.0      # `codex login --with-api-key` (локально, без сети)


async def _kill_reap(proc) -> None:
    """M1: зависший подпроцесс — убить и дождаться (без зомби и утечки fd)."""
    try:
        proc.kill()
    except ProcessLookupError:
        pass
    await proc.wait()


async def apply_alt(rec: dict) -> None:
    """Применить режим после записи auth.codex.json: ключ OpenAI → `codex login
    --with-api-key` в альт-каталоге (stdin), шлюз → без auth.json. Пустой rec — снести
    альт-каталог. Бросает RuntimeError, если вход ключом не удался."""
    import asyncio
    from . import auth_store
    home = alt_home()
    if home is None:
        return
    if not rec:
        auth_store.rmtree_logged(home)
        return
    prepare_alt_home()
    (home / "auth.json").unlink(missing_ok=True)
    if rec.get("method") != "api_key":
        return
    binary = cli_registry.find_binary(CLI_TYPE)
    if binary is None:
        raise RuntimeError("codex CLI is not installed")
    proc = await asyncio.create_subprocess_exec(
        binary, "login", "--with-api-key", stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT,
        env=cli_registry.spawn_env(CLI_TYPE, binary, {"CODEX_HOME": str(home)}))
    try:
        out, _ = await asyncio.wait_for(
            proc.communicate(rec["api_key"].encode()), _LOGIN_KEY_TIMEOUT)
    except asyncio.TimeoutError:
        await _kill_reap(proc)
        raise RuntimeError("codex login --with-api-key timed out") from None
    except asyncio.CancelledError:
        await _kill_reap(proc)
        raise
    if proc.returncode != 0:
        from .secrets_redact import redact
        raise RuntimeError(redact(out.decode(errors="replace")[-200:]))
    try:
        os.chmod(home / "auth.json", 0o600)     # ключ OpenAI лежит открытым текстом
    except OSError as e:
        log.warning("codex_auth.chmod_failed", err=str(e))


def codex_home() -> Path:
    return Path(os.environ.get("CODEX_HOME") or (Path.home() / ".codex"))


def token_path() -> Path:
    """Файл учётных данных Codex (env HEDGEHOG_CODEX_TOKEN переопределяет)."""
    override = os.environ.get("HEDGEHOG_CODEX_TOKEN")
    return Path(override) if override else codex_home() / "auth.json"


def is_logged_in() -> bool:
    p = token_path()
    try:
        if not p.is_file() or p.stat().st_size == 0:
            return False
        data = json.loads(p.read_text("utf-8"))
    except (OSError, ValueError):
        return False
    return isinstance(data, dict) and bool(
        data.get("tokens") or data.get("OPENAI_API_KEY"))


def logout() -> bool:
    p = token_path()
    try:
        existed = p.exists()
        p.unlink(missing_ok=True)
        return existed
    except OSError as e:
        log.warning("codex_auth.logout_failed", err=str(e))
        return False


_LOGIN_HOSTS = ("openai.com", "chatgpt.com")


def _is_login_url(url: str) -> bool:
    """Только https и хост openai.com/chatgpt.com (или их поддомен) — точное
    сравнение хоста, не подстрока (защита от подсунутой в вывод чужой ссылки)."""
    from urllib.parse import urlsplit
    try:
        u = urlsplit(url)
        host = (u.hostname or "").lower()
    except ValueError:
        return False
    return u.scheme == "https" and any(
        host == h or host.endswith("." + h) for h in _LOGIN_HOSTS)


def parse_device_login(text: str) -> tuple[str | None, str | None]:
    """Из вывода `codex login --device-auth`: (ссылка, одноразовый код)."""
    url = code = None
    for line in _ANSI_RE.sub("", text).splitlines():
        line = line.strip()
        if url is None:
            m = _URL_RE.search(line)
            if m and _is_login_url(m.group(0)):
                url = m.group(0)
                continue
        if code is None and _CODE_RE.match(line):
            code = line
    return url, code


class CodexAuthManager(SubprocessAuthFlow):
    CLI = CLI_TYPE
    TAG = "codex-auth"
    needs_code = False        # код вводится на сайте, а не присылается в Ёжик

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._link: dict | None = None

    def default_argv(self, binary: str) -> list[str]:
        return [binary, "login", "--device-auth"]

    def _reset(self) -> None:
        self._link, self._tail = None, []

    async def start(self) -> None:
        if self.running:
            if self._link:
                await self._broadcast("auth_link", {
                    **self._link, "already_running": True})
            return
        if is_logged_in():
            # `codex login --device-auth` СРАЗУ стирает действующий вход —
            # не запускаем поверх живого токена (сначала явный logout).
            # H1: ok:false — входа не было; клиент покажет подсказку «выйдите и
            # войдите заново», сервер НЕ перезапускает сессии CLI
            await self._broadcast("auth_result", {
                "ok": False, "already_logged_in": True,
                "error": Msg("auth.already_logged_in")})
            return
        self._task = asyncio.create_task(self._flow(), name="codex-auth")

    async def submit_code(self, code: str) -> bool:
        return False

    async def _pump(self) -> None:
        assert self._proc is not None and self._proc.stdout is not None
        seen = ""
        async for raw in self._proc.stdout:
            line = _ANSI_RE.sub("", raw.decode(errors="replace")).rstrip()
            self._note(line)
            seen += line + "\n"
            if self._link is None:
                url, code = parse_device_login(seen)
                if url and code:
                    self._link = {"url": url, "userCode": code}
                    await self._broadcast("auth_link", dict(self._link))
        rc = await self._proc.wait()
        if rc == 0 and is_logged_in():
            log.info("codex_auth.ok")
            await self._broadcast("auth_result", {"ok": True})
        else:
            await self._broadcast("auth_result", {
                "ok": False,
                "error": f"codex login failed (exit {rc}): "
                         + " | ".join(self._tail[-3:])[:300]})
